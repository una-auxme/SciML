#!/usr/bin/env python3
"""
Update data/github_stars.json with the current number of GitHub stars of every package
listed in data/software.toml (field `repo`). The software page shows these numbers.

Runs at every build of the site (.github/workflows/deploy.yml); the result is not committed, the
numbers in the repository are only a fallback. Uses the GITHUB_TOKEN
environment variable if it is set (higher rate limit); works without it, too.
If a repository cannot be reached, its previous number is kept.

Needs Python 3.11 or newer and no third-party packages.

Usage
  python scripts/update_github_stars.py
"""

from __future__ import annotations

import json
import os
import re
import sys
import tomllib
import urllib.error
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOFTWARE_FILE = ROOT / "data" / "software.toml"
OUTPUT_FILE = ROOT / "data" / "github_stars.json"


def repo_key(url: str) -> str | None:
    """'https://github.com/JuliaFMI/FMI.jl' -> 'JuliaFMI/FMI.jl' (None for non-GitHub URLs)."""
    m = re.match(r"https?://(?:www\.)?github\.com/([^/\s]+)/([^/\s#?]+)", url or "")
    return f"{m.group(1)}/{m.group(2).removesuffix('.git')}" if m else None


def fetch_stars(key: str) -> int:
    req = urllib.request.Request(f"https://api.github.com/repos/{key}", headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "group-website-star-sync/1.0",
        **({"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}"} if os.environ.get("GITHUB_TOKEN") else {}),
    })
    with urllib.request.urlopen(req, timeout=30) as resp:
        return int(json.load(resp)["stargazers_count"])


def main() -> None:
    with SOFTWARE_FILE.open("rb") as fh:
        packages = tomllib.load(fh).get("package", [])
    previous = json.loads(OUTPUT_FILE.read_text(encoding="utf-8")) if OUTPUT_FILE.exists() else {}
    old_stars = previous.get("stars", {})

    stars, failed = {}, []
    for pkg in packages:
        key = repo_key(pkg.get("repo", ""))
        if not key:
            continue
        try:
            stars[key] = fetch_stars(key)
            print(f"{key}: {stars[key]} stars", file=sys.stderr)
        except (urllib.error.URLError, TimeoutError, KeyError, ValueError) as e:
            failed.append(key)
            if key in old_stars:
                stars[key] = old_stars[key]
            print(f"warning: could not read {key} ({e}); keeping {old_stars.get(key, 'no')} previous value",
                  file=sys.stderr)

    changed = stars != old_stars
    result = {
        "_comment": "Generated by scripts/update_github_stars.py. Do not edit by hand.",
        "updated": date.today().isoformat() if changed else previous.get("updated", date.today().isoformat()),
        "stars": dict(sorted(stars.items())),
    }
    OUTPUT_FILE.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    print(f"wrote stars for {len(stars)} repositories to {OUTPUT_FILE.relative_to(ROOT)}"
          f"{'' if changed else ' (unchanged)'}", file=sys.stderr)
    if failed and len(failed) == len([p for p in packages if repo_key(p.get("repo", ""))]):
        sys.exit("error: no repository could be read")


if __name__ == "__main__":
    main()
